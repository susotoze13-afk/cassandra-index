// Правовая рамка репозитория (R01/R01i/R02/R02ii/R03/R03i/R05/R05i/R08ii/R10i).
// Ожидания — из спецификации и первоисточников лицензий, не из содержимого файлов
// под тестом. Эталонные фрагменты скопированы из
// https://www.apache.org/licenses/LICENSE-2.0.txt и
// https://creativecommons.org/licenses/by/4.0/legalcode.txt как есть: сравнение
// идёт с точным сегментом, а не с длиной файла.
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (name) => readFileSync(join(root, name), 'utf8');
const norm = (text) => text.replace(/\r\n/g, '\n');
// Перенос строк в прозе — форматирование, а не содержание: фразу сверяем без него.
const flatten = (text) => norm(text).replace(/\s+/g, ' ');

const APACHE_URL = 'http://www.apache.org/licenses/LICENSE-2.0';
