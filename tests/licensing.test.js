const MARKUP_BOUNDARY = 'Текст страниц — CC BY 4.0 (LICENSE-DOCS); разметка и стили тех же страниц (*.html, css/**) — Apache License 2.0 (LICENSE).';

// Фраза о невхождении дампов GeoNames (R02ii).
const GEONAMES_DUMPS = 'Дампы GeoNames (data/geo/*.zip, *.txt, cities15000.*, countryInfo.*) в репозиторий не входят (.gitignore).';

test('LICENSE: дословный Apache-2.0, одно заполненное приложение и область применения', () => {
  const license = norm(read('LICENSE'));

  // Точный канонический сегмент первоисточника, а не порог длины.
  assert.ok(license.includes(APACHE_HEADER), 'нет заголовка Apache-2.0 дословно');
  assert.ok(license.includes(APACHE_SEGMENT), 'сегмент §4(d) Apache-2.0 отличается от первоисточника');
  assert.ok(license.includes('END OF TERMS AND CONDITIONS'), 'нет конца условий Apache-2.0');
  assert.ok(license.includes(APACHE_URL), 'нет canonical URL текста Apache-2.0');

  // Ровно одно приложение — и оно заполнено.
  const appendixHeading = 'APPENDIX: How to apply the Apache License to your work.';
  assert.equal(license.split('APPENDIX:').length - 1, 1, 'приложение должно быть одно');
  const appendix = license.slice(license.indexOf(appendixHeading));
  assert.ok(appendix.includes(`   ${COPYRIGHT}`), 'приложение не заполнено строкой правообладателя');
  assert.ok(!appendix.includes('   Copyright [yyyy] [name of copyright owner]'),
    'шаблонная строка copyright осталась незаполненной');
  assert.ok(flatten(license).includes('Других приложений в файле нет.'),
    'граница приложения описана неверно');

  // Структура области применения — как у LICENSE-DATA/LICENSE-DOCS (R02ii).
  assert.ok(license.includes('Область применения'), 'нет раздела «Область применения»');
  assert.ok(license.includes('Что покрыто этой лицензией'), 'нет списка покрытого');
  assert.ok(license.includes('Что НЕ покрыто этой лицензией'), 'нет списка непокрытого');
  assert.ok(license.includes(MARKUP_BOUNDARY), 'нет фразы о границе разметки и текста страниц');
  assert.ok(license.includes('LICENSE-DATA'), 'нет ссылки на лицензию данных');
  assert.ok(license.includes('LICENSE-DOCS'), 'нет ссылки на лицензию документов');
  assert.ok(license.includes('NOTICE'), 'нет ссылки на NOTICE (R01.1)');
  assert.ok(license.includes('TRADEMARK.md'), 'нет ссылки на TRADEMARK.md (R05)');

  // Старая двусмысленность «HTML и CSS целиком под Apache» не возвращается.
  assert.ok(!license.includes('HTML и CSS)'), 'разметка и код снова объявлены одной скобкой');
});

const ccBody = (name) => {
  const text = norm(read(name));
  const parts = text.split(CC_BODY_MARKER);
  assert.equal(parts.length, 2, `${name}: нет маркера начала полного текста CC BY 4.0`);
  return { header: parts[0], body: parts[1] };
};

test('LICENSE-DATA: область применения, атрибуция и дословный CC BY 4.0', () => {
  const { header, body } = ccBody('LICENSE-DATA');

  assert.ok(header.includes('Область применения'), 'нет раздела «Область применения»');
  assert.ok(header.includes('Что покрыто этой лицензией'), 'нет списка покрытого');
  assert.ok(header.includes('Что НЕ покрыто этой лицензией'), 'нет списка непокрытого');
  assert.ok(header.includes('data/**'), 'шапка должна называть покрытый путь data/**');
  assert.ok(header.includes('Apache License 2.0') || header.includes('Apache-2.0'),
    'шапка должна говорить, что код покрыт Apache-2.0');
  assert.ok(flatten(header).includes(GEONAMES_DUMPS), 'нет точной фразы о невхождении дампов GeoNames');
  assert.ok(header.includes('издател'), 'шапка должна говорить, что тексты источников — права издателей');
  assert.ok(header.includes(`${SITE}, лицензия CC BY 4.0`), 'нет строки атрибуции с сайтом');
  assert.ok(header.includes('TRADEMARK.md'), 'шапка должна ссылаться на TRADEMARK.md (R05)');
  assert.ok(header.includes(CC_BY_URL), 'нет canonical URL CC BY 4.0');
  assert.ok(header.includes(MARKUP_BOUNDARY), 'нет фразы о границе разметки и текста страниц');

  assert.ok(body.includes(CC_SEGMENT), 'сегмент Section 4 CC BY 4.0 отличается от первоисточника');
  assert.ok(body.includes('Creative Commons Corporation'), 'нет текста legalcode');
});

