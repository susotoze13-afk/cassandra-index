test('в трекинге нет закрытых каталогов commercial/, private/, enterprise/', (t) => {
  let tracked;
  try {
    tracked = execFileSync('git', ['-C', root, 'ls-files'], { encoding: 'utf8' })
      .split('\n')
      .map((line) => line.trim())
      .filter(Boolean);
  } catch (error) {
    if (error.code === 'ENOENT') {
      t.skip('git не найден в PATH — проверка трекинга пропущена');
      return;
    }
    throw error;
  }

  for (const dir of ['commercial/', 'private/', 'enterprise/']) {
    const leaked = tracked.filter((path) => path.startsWith(dir));
    assert.deepEqual(leaked, [], `закрытый каталог ${dir} не должен быть в трекинге`);
  }
});
